export const DEFAULT_ACCENT = "mint";
export const ACCENT_IDS = Object.keys(ACCENT_PALETTES);

export function applyAccentVariables(accentId, theme) {
  const palette = ACCENT_PALETTES[accentId] ?? ACCENT_PALETTES[DEFAULT_ACCENT];
  const root = document.documentElement;
  const merged = { ...palette.vars, ...(theme === "dark" ? palette.varsDark : {}) };
  for (const [key, value] of Object.entries(merged)) {
    root.style.setProperty(key, value);
  }
  root.setAttribute("data-accent", palette.id);
}

export function getChartColors(accentId) {
  const palette = ACCENT_PALETTES[accentId] ?? ACCENT_PALETTES[DEFAULT_ACCENT];
  return palette.chart;
}
